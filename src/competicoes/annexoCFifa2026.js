/** Chave é combinação ordenada de 8 letras, ex.: ABCDEFGH. */
export function alocacaoOficialTerceirosFifa26(letras){
 const chave=combinacao(letras);
 if(chave.length!==8||new Set(chave).size!==8)throw new Error('São necessários oito grupos terceiros diferentes.');
 const linha=mapa.get(chave);
 if(!linha)throw new Error('Combinação sem correspondência no Anexo C da FIFA.');
 return Object.fromEntries(ORDEM_VENCEDORES_ANEXO_C.map((v,i)=>[v,linha[i]]));
}
